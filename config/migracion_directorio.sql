
CREATE TABLE IF NOT EXISTS directorio_instituciones (
  id            INT UNSIGNED NOT NULL AUTO_INCREMENT,
  categoria     VARCHAR(20)  NOT NULL DEFAULT 'universidad',   
  sigla         VARCHAR(30)  NULL,
  nombre        VARCHAR(200) NOT NULL,
  tipo          VARCHAR(30)  NULL,   
  regimen       TEXT         NULL,
  anio_creacion VARCHAR(80)  NULL,
  sedes         TEXT         NULL,
  direccion     TEXT         NULL,
  telefono      VARCHAR(80)  NULL,
  sitio_web     VARCHAR(150) NULL,
  observaciones TEXT         NULL,
  PRIMARY KEY (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS carreras (
  id     INT UNSIGNED NOT NULL AUTO_INCREMENT,
  nombre VARCHAR(200) NOT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uq_carrera_nombre (nombre)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS institucion_carrera (
  id             INT UNSIGNED NOT NULL AUTO_INCREMENT,
  institucion_id INT UNSIGNED NOT NULL,
  carrera_id     INT UNSIGNED NOT NULL,
  facultad       VARCHAR(200) NULL,
  grado          VARCHAR(40)  NOT NULL,                       
  duracion       VARCHAR(80)  NULL,                           
  observaciones  TEXT         NULL,
  PRIMARY KEY (id),
  KEY idx_institucion (institucion_id),
  KEY idx_carrera (carrera_id),
  CONSTRAINT fk_ic_institucion FOREIGN KEY (institucion_id) REFERENCES directorio_instituciones (id) ON DELETE CASCADE,
  CONSTRAINT fk_ic_carrera     FOREIGN KEY (carrera_id)     REFERENCES carreras (id)                ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

